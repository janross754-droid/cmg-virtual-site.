-- CMG VIRTUAL historical settled-selection ledger
create table if not exists public.cmg_historical_results (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  ticket_id text not null,
  match_date date,
  league text not null,
  fixture text not null,
  market text not null,
  selection text not null,
  odds numeric(8,3) not null check (odds > 1),
  home_score integer not null check (home_score >= 0),
  away_score integer not null check (away_score >= 0),
  outcome text not null check (outcome in ('Home','Draw','Away')),
  selection_correct boolean not null,
  created_at timestamptz not null default now(),
  unique (user_id, ticket_id, fixture, market)
);
create index if not exists cmg_historical_results_user_date_idx
  on public.cmg_historical_results (user_id, match_date desc);
alter table public.cmg_historical_results enable row level security;
drop policy if exists "Users read own CMG historical results" on public.cmg_historical_results;
create policy "Users read own CMG historical results"
  on public.cmg_historical_results for select to authenticated
  using (auth.uid() = user_id);
drop policy if exists "Users insert own CMG historical results" on public.cmg_historical_results;
create policy "Users insert own CMG historical results"
  on public.cmg_historical_results for insert to authenticated
  with check (auth.uid() = user_id);
drop policy if exists "Users delete own CMG historical results" on public.cmg_historical_results;
create policy "Users delete own CMG historical results"
  on public.cmg_historical_results for delete to authenticated
  using (auth.uid() = user_id);
